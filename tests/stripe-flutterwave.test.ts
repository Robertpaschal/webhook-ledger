import Stripe from "stripe";
import { describe, expect, it } from "vitest";
import { verifyFlutterwave, verifyStripe } from "../src/index.js";
import { flutterwaveChargeCompleted, stripePaymentIntentSucceeded as stripeBody } from "./fixtures/payloads.js";
import { NOW, signStripe } from "./helpers.js";

const STRIPE_SECRET = "whsec_test_stripe_secret_000000000000";
const FLW_HASH = "my-flutterwave-secret-hash";

describe("Stripe-Signature", () => {
  it("accepts a header generated by Stripe's own SDK", () => {
    const stripe = new Stripe("sk_test_unused");
    const header = stripe.webhooks.generateTestHeaderString({ payload: stripeBody, secret: STRIPE_SECRET, timestamp: NOW });
    const r = verifyStripe({ rawBody: stripeBody, headers: { "stripe-signature": header }, now: NOW }, { signingSecret: STRIPE_SECRET });
    expect(r).toMatchObject({ ok: true, eventKey: "evt_3TestEventId0001", eventType: "payment_intent.succeeded" });
  });

  it("agrees with Stripe's SDK on a header this suite signs", () => {
    const header = signStripe(stripeBody, STRIPE_SECRET, NOW);
    const stripe = new Stripe("sk_test_unused");
    expect(() => stripe.webhooks.constructEvent(stripeBody, header, STRIPE_SECRET, Number.MAX_SAFE_INTEGER)).not.toThrow();
  });

  it("rejects tampering, staleness and wrong secrets", () => {
    const header = signStripe(stripeBody, STRIPE_SECRET);
    expect(verifyStripe({ rawBody: stripeBody.replace("2000", "20"), headers: { "stripe-signature": header }, now: NOW }, { signingSecret: STRIPE_SECRET })).toMatchObject({ ok: false, reason: "signature_mismatch" });
    expect(verifyStripe({ rawBody: stripeBody, headers: { "stripe-signature": header }, now: NOW + 301 }, { signingSecret: STRIPE_SECRET })).toMatchObject({ ok: false, reason: "timestamp_outside_tolerance" });
    expect(verifyStripe({ rawBody: stripeBody, headers: { "stripe-signature": header }, now: NOW }, { signingSecret: "whsec_other" })).toMatchObject({ ok: false, reason: "signature_mismatch" });
    expect(verifyStripe({ rawBody: stripeBody, headers: {}, now: NOW }, { signingSecret: STRIPE_SECRET })).toMatchObject({ ok: false, reason: "missing_signature" });
    expect(verifyStripe({ rawBody: stripeBody, headers: { "stripe-signature": "v0=abc" }, now: NOW }, { signingSecret: STRIPE_SECRET })).toMatchObject({ ok: false, reason: "malformed_signature" });
  });

  it("accepts the matching secret among several (rotation) and ignores v0", () => {
    const header = `${signStripe(stripeBody, STRIPE_SECRET)},v0=deadbeef`;
    const r = verifyStripe({ rawBody: stripeBody, headers: { "stripe-signature": header }, now: NOW }, { signingSecret: ["whsec_old", STRIPE_SECRET] });
    expect(r.ok).toBe(true);
  });
});

describe("Flutterwave verif-hash", () => {
  it("accepts the configured secret hash", () => {
    const r = verifyFlutterwave({ rawBody: flutterwaveChargeCompleted, headers: { "verif-hash": FLW_HASH } }, { secretHash: FLW_HASH });
    expect(r).toMatchObject({ ok: true, eventKey: "charge.completed:285959875", eventType: "charge.completed", scheme: "verif-hash" });
  });

  it("rejects a wrong or missing hash", () => {
    expect(verifyFlutterwave({ rawBody: flutterwaveChargeCompleted, headers: { "verif-hash": "nope" } }, { secretHash: FLW_HASH })).toMatchObject({ ok: false, reason: "signature_mismatch" });
    expect(verifyFlutterwave({ rawBody: flutterwaveChargeCompleted, headers: { "verif-hash": `${FLW_HASH}x` } }, { secretHash: FLW_HASH })).toMatchObject({ ok: false, reason: "signature_mismatch" });
    expect(verifyFlutterwave({ rawBody: flutterwaveChargeCompleted, headers: {} }, { secretHash: FLW_HASH })).toMatchObject({ ok: false, reason: "missing_signature" });
    expect(verifyFlutterwave({ rawBody: flutterwaveChargeCompleted, headers: { "verif-hash": "" } }, { secretHash: "" })).toMatchObject({ ok: false, reason: "no_secret_configured" });
  });

  it("rejects a body that is not JSON", () => {
    expect(verifyFlutterwave({ rawBody: "not json", headers: { "verif-hash": FLW_HASH } }, { secretHash: FLW_HASH })).toMatchObject({ ok: false, reason: "invalid_json" });
  });
});
